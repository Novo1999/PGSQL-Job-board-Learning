// ============================================================================
// guard-exercise-files.mjs — turn the AGENTS.md contract into an actual guard
// ============================================================================
// Wired up as a Claude Code PreToolUse hook in .claude/settings.json. It reads
// the pending tool call on stdin and decides what happens to it:
//
//   src/controllers/**   ->  "ask"   the human must approve, because the SQL in
//                                    these files is the exercise and an agent
//                                    writing it is the one failure mode this
//                                    repository cares about
//   postman/*.json       ->  "deny"  generated by `npm run postman`
//   docs/API.md          ->  "deny"  same
//   sql/schema.sql|seed  ->  "ask"   deliberately shaped teaching data
//   everything else      ->  silence, which means "carry on"
//
// It is a speed bump, not a lock: "ask" still lets the human say yes, and
// deleting .claude/settings.json removes the hook entirely. Nothing else in the
// project depends on this file.
//
// Contract: https://docs.claude.com/en/docs/claude-code/hooks
// ============================================================================

const RULES = [
  {
    test: (path) => /(^|[\\/])src[\\/]controllers[\\/]/.test(path),
    decision: 'ask',
    reason:
      'This file is a SQL exercise (see AGENTS.md). The empty pool.query(``) sites here are ' +
      'the whole point of the repository, and filling one in on the learner\'s behalf is the ' +
      'one thing this project asks agents not to do.\n\n' +
      'If you were about to write or complete a query: stop, and offer a hint instead — what ' +
      'tables the answer needs, what one row of the result looks like, or what is wrong with ' +
      'the attempt so far.\n\n' +
      'If the human explicitly asked for the finished query, or this edit is unrelated to the ' +
      'SQL (a typo, a type, a comment), say which and let them approve it.',
  },
  {
    test: (path) => /(^|[\\/])postman[\\/].*\.json$/.test(path) || /(^|[\\/])docs[\\/]API\.md$/.test(path),
    decision: 'deny',
    reason:
      'This file is generated from src/routes and src/controllers. Hand-editing it will be ' +
      'overwritten and makes the docs disagree with the code.\n\n' +
      'Change the source instead — the route, the handler, or the comment above it — then run ' +
      '`npm run postman`. Example bodies and request names live in scripts/api-examples.ts.',
  },
  {
    test: (path) => /(^|[\\/])sql[\\/](schema|seed)\.sql$/.test(path),
    decision: 'ask',
    reason:
      'The schema and the seed data are deliberate teaching material (see CONTEXT.md). The ' +
      'missing index, the open-but-expired posting, the candidate with no skills and the job ' +
      'with NULL salaries all exist to make some query interesting.\n\n' +
      'If this is a real change the human wants, explain what it changes about the exercises ' +
      'and let them approve it.',
  },
];

function pathsFrom(toolInput) {
  if (!toolInput || typeof toolInput !== 'object') return [];

  const candidates = [
    toolInput.file_path,
    toolInput.notebook_path,
    toolInput.path,
    ...(Array.isArray(toolInput.edits) ? toolInput.edits.map((edit) => edit?.file_path) : []),
  ];

  return candidates.filter((value) => typeof value === 'string' && value.length > 0);
}

function decide(paths) {
  for (const path of paths) {
    const normalised = path.replace(/\\/g, '/');
    for (const rule of RULES) {
      if (rule.test(normalised)) return { rule, path: normalised };
    }
  }
  return null;
}

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString('utf8');
}

const raw = await readStdin();

let payload;
try {
  payload = JSON.parse(raw);
} catch {
  // A hook that cannot parse its input must not block the session.
  process.exit(0);
}

const match = decide(pathsFrom(payload.tool_input));
if (!match) process.exit(0);

process.stdout.write(
  `${JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: match.rule.decision,
      permissionDecisionReason: match.rule.reason,
    },
  })}\n`
);
